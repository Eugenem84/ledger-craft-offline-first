// src/utils/hints.js
//
// Подсказки интерфейса — настройка устройства (правка владельца 26.09.2026:
// «по приложению есть подсказки. Они занимают место. Нужно сделать их мельче в два раза
// и опционально по умолчанию выключать в настройках»).
//
// Поэтому подсказки — это **управляемый** слой, а не текст по месту:
//   • флаг `hintsEnabled` (localStorage) — одна точка на всё приложение; **по умолчанию
//     выключен**, потому что мастер попросил именно так;
//   • все подсказки выводятся компонентом `components/ui/LcHint.vue`, который читает этот
//     флаг и при выключенном значении не рендерится вовсе — место не занимает;
//   • включённые подсказки показываются уменьшенным шрифтом (класс `.lc-hint`, правка
//     «мельче в два раза» — вдвое мельче базового текста приложения).
//
// Флаг — обычный `ref`, как `utils/devMode.js`: его читают компоненты до/вне Pinia,
// и лишняя зависимость от стора здесь ни к чему. Хранение — `localStorage` (ключ `'1'`/`'0'`),
// потому что это настройка **устройства**, а не профиля: синком она не уезжает.
import { ref } from 'vue'
import storage from 'src/utils/storage.js'

/** Ключ хранения. Значение `'1'`/`'0'` — как у остальных служебных флагов. */
export const HINTS_KEY = 'ui_hints_enabled'

/**
 * Реактивный флаг: `true` — подсказки показываем. Умолчание — `false`
 * («опционально по умолчанию выключать в настройках»).
 */
export const hintsEnabled = ref(storage.getItem(HINTS_KEY) === '1')

/** Включены ли подсказки прямо сейчас (без реактивности). */
export function isHintsEnabled() {
  return hintsEnabled.value === true
}

/** Включает/выключает подсказки и запоминает выбор. Возвращает новое значение. */
export function setHints(value) {
  hintsEnabled.value = value === true
  storage.trySetItem(HINTS_KEY, hintsEnabled.value ? '1' : '0')

  return hintsEnabled.value
}

/** Переключает подсказки. */
export function toggleHints() {
  return setHints(!hintsEnabled.value)
}
