// src/utils/releaseNotes.js
//
// «Что нового» из ответа сервера — списком пунктов (правка владельца 15.09.2026).
//
// Релизные заметки приезжают одной строкой («Чиним склад, Ускорили синк»), а в
// карточке обновления их нужно показать **списком через тире**: перечисление через
// запятую сливалось в кашу и не читалось на телефоне. Разделителями считаем запятую,
// точку с запятой и перевод строки — так заметки можно писать и в одну строку, и
// столбиком. Маркер списка («—», «-», «•»), если он уже есть в тексте, не дублируем.

/**
 * @param {unknown} notes строка заметок релиза (`notes` из `/app-version`)
 * @returns {string[]} пункты «что нового» (пустые отброшены; мусор → пустой список)
 */
export function parseReleaseNotes(notes) {
  if (notes == null) return []

  return String(notes)
    .split(/[\n\r;,]+/)
    .map(item => item.replace(/^[\s\-–—•*·]+/, '').trim())
    .filter(Boolean)
}
