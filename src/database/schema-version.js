// src/database/schema-version.js
//
// «Эталон» схемы локальной БД (Фаза 2) в виде версии — задача 4.5.
//
// Версия схемы = количество миграций в списке. Миграции только добавляются (номера не
// переиспользуются — см. 2.1), поэтому число растёт монотонно и однозначно описывает
// набор миграций в таблице `migrations`.
//
// Как это связано с плагином. В @capacitor-community/sqlite v4 был метод `setVersion`,
// но в текущей линии (7.x) его нет: версия схемы хранится в самой БД — в
// `PRAGMA user_version`, и именно её возвращает нативный `getVersion()`. Поэтому
// нативный адаптер читает/пишет `user_version` (getSchemaVersion/setSchemaVersion),
// а `boot/db.js` после прогона миграций сверяет её с этим эталоном и при расхождении
// записывает эталон заново. Собственный JS-раннер миграций остаётся единственным
// механизмом изменения схемы (per-table `upgrade`-скрипты плагина не используются:
// миграции Фазы 2 — это JS-функции, а не SQL-строки).
import migrations from './migrations/index.js'

export const SCHEMA_VERSION = migrations.length
